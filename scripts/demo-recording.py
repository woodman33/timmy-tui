#!/usr/bin/env python3
# R9 lead: the review package's demo recording, so tab 6 (3D & Motion) has a Rerun recording (.rrd) to list and read: the
# demo tray of scripts/demo-mesh.mjs (80 x 50 x 20, walls 3, floor 2), logged as Rerun data by the Rerun SDK. It is a
# generated recording, never a capture of a camera, a sensor or a physical part, and its own words say so (the store's
# application id and the /notes text it holds).
#
#   python3 scripts/demo-recording.py        writes examples/visual-tools/demo-tray.rrd (needs the rerun-sdk package)
#
# What it holds (what tab 6 reads back through the installed Rerun CLI, src/vox/rrd-cli.ts):
#   entities   /tray/box (the tray's outer box, Boxes3D), /tray/corners (its 8 outer corners, Points3D), /tray/floor (the
#              inner floor's corners rising frame by frame, Points3D), /notes (a static TextLog saying what this file is),
#              and the SDK's own /__properties (the recording's start time)
#   timelines  frame (a sequence, 0 to 7) and t (a duration, 0 to 0.7 s), and the SDK's own log_time
#
# The recording id is given here, not drawn at random; the SDK stamps each row with its log_time (the clock when this script
# ran), so a second run writes the same entities and frame and t ranges with other log_time values: the committed file is
# the one written once, by rerun-sdk 0.38.1.
import sys

import rerun as rr

OUT = sys.argv[1] if len(sys.argv) > 1 else "examples/visual-tools/demo-tray.rrd"
L, W, H, WALL, FLOOR = 80.0, 50.0, 20.0, 3.0, 2.0

rr.init("timmy_demo_generated_tray", recording_id="timmy-demo-tray-1")
rr.save(OUT)
rr.log(
    "notes",
    rr.TextLog("TIMMY DEMO RECORDING: generated by scripts/demo-recording.py from the demo tray's dimensions; not a capture"),
    static=True,
)
rr.log("tray/box", rr.Boxes3D(centers=[[L / 2, W / 2, H / 2]], half_sizes=[[L / 2, W / 2, H / 2]]), static=True)
corners = [[x, y, z] for z in (0.0, H) for y in (0.0, W) for x in (0.0, L)]
for frame in range(8):
    rr.set_time("frame", sequence=frame)
    rr.set_time("t", duration=frame * 0.1)
    rr.log("tray/corners", rr.Points3D(corners))
    z = FLOOR * frame / 7
    floor = [[WALL, WALL, z], [L - WALL, WALL, z], [L - WALL, W - WALL, z], [WALL, W - WALL, z]]
    rr.log("tray/floor", rr.Points3D(floor))
