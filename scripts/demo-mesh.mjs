#!/usr/bin/env node
// R7 (H153): the review package's demo mesh, so tab 6 (3D & Motion) has a mesh to list and draw: a tray, generated here
// from its dimensions (no CAD program, no scan, no export from anything), as a binary STL. It is a generated mesh, never a
// measurement or an export of a physical part, and its 80-byte header says so in the file itself.
//
//   node scripts/demo-mesh.mjs           writes examples/visual-tools/demo-tray.stl
//   node scripts/demo-mesh.mjs --check   exits 1 when the committed file is not what this script writes
//
// The tray: 80 × 50 × 20 (x, y, z; the file's own units, millimetres by the STL convention), walls 3 thick, a floor 2 thick,
// open at the top: a closed, consistently oriented mesh of 28 triangles, each one's corners counter-clockwise seen from
// outside (its stored normal is the corners' own), so Timmy's STL reader measures an enclosed volume of
// 80 × 50 × 20 − 74 × 44 × 18 = 21392.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { resolve } from 'node:path';

export const DEMO_MESH = 'examples/visual-tools/demo-tray.stl';
/** The file's own words (at most 80 bytes): what made it, and what it is not. */
export const DEMO_HEADER = 'TIMMY DEMO MESH: generated by scripts/demo-mesh.mjs, not measured or exported';
export const DEMO_TRAY = { length: 80, width: 50, height: 20, wall: 3, floor: 2 };

/** The tray's triangles, each three corners [x, y, z], counter-clockwise seen from outside. */
export function trayTriangles({ length: L, width: W, height: H, wall: t, floor: f } = DEMO_TRAY) {
  const B = [[0, 0, 0], [L, 0, 0], [L, W, 0], [0, W, 0]];
  const O = B.map(([x, y]) => [x, y, H]);
  const I = [[t, t, H], [L - t, t, H], [L - t, W - t, H], [t, W - t, H]];
  const F = I.map(([x, y]) => [x, y, f]);
  const quad = (a, b, c, d) => [[a, b, c], [a, c, d]];
  const tris = [];
  tris.push([B[0], B[3], B[2]], [B[0], B[2], B[1]]); // the bottom, facing -z
  for (let k = 0; k < 4; k += 1) {
    const n = (k + 1) % 4;
    tris.push(...quad(B[k], B[n], O[n], O[k])); // an outer wall, facing out
    tris.push(...quad(O[k], O[n], I[n], I[k])); // the rim, facing +z
    tris.push([F[k], I[n], F[n]], [F[k], I[k], I[n]]); // an inner wall, facing into the pocket
  }
  tris.push([F[0], F[1], F[2]], [F[0], F[2], F[3]]); // the pocket's floor, facing +z
  return tris;
}

/** The demo mesh's bytes: the header, the count, then each triangle's unit normal, corners and a zero attribute. */
export function demoTrayStl() {
  const tris = trayTriangles();
  const b = Buffer.alloc(84 + 50 * tris.length);
  if (Buffer.byteLength(DEMO_HEADER, 'latin1') > 80) throw new Error('the header is longer than 80 bytes');
  b.write(DEMO_HEADER, 0, 'latin1');
  b.writeUInt32LE(tris.length, 80);
  tris.forEach(([a, c, d], i) => {
    const u = [c[0] - a[0], c[1] - a[1], c[2] - a[2]];
    const v = [d[0] - a[0], d[1] - a[1], d[2] - a[2]];
    const n = [u[1] * v[2] - u[2] * v[1], u[2] * v[0] - u[0] * v[2], u[0] * v[1] - u[1] * v[0]];
    const len = Math.hypot(...n);
    const at = 84 + i * 50;
    n.forEach((x, j) => b.writeFloatLE(x / len, at + j * 4));
    [a, c, d].forEach((p, k) => p.forEach((x, j) => b.writeFloatLE(x, at + 12 + k * 12 + j * 4)));
  });
  return b;
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const file = fileURLToPath(new URL(`../${DEMO_MESH}`, import.meta.url));
  const want = demoTrayStl();
  if (process.argv.includes('--check')) {
    let have = Buffer.alloc(0);
    try { have = readFileSync(file); } catch { /* missing */ }
    if (!have.equals(want)) { console.error(`${DEMO_MESH} is not what scripts/demo-mesh.mjs writes: run it again`); process.exit(1); }
    console.log(`${DEMO_MESH}: as scripts/demo-mesh.mjs writes it (${want.length} bytes)`);
  } else {
    writeFileSync(file, want);
    console.log(`wrote ${DEMO_MESH} (${want.length} bytes, generated: not measured or exported)`);
  }
}
