#!/usr/bin/env node
// R7 (H153): the review package's demo mesh, so tab 6 (3D & Motion) has a mesh to list and draw: a tray, generated here
// from its dimensions (no CAD program, no scan, no export from anything), as a binary STL. It is a generated mesh, never a
// measurement or an export of a physical part, and its 80-byte header says so in the file itself.
// R8 (H154): the same tray as a Wavefront OBJ and a binary little-endian PLY, so a reviewer sees three kinds: written here from
// the same triangles (each pair of them one quad, whose fan from its first corner gives the STL's two triangles in the STL's
// order), never measured or exported by any tool, each saying so in its own first comment. Timmy's own STL, OBJ and PLY
// readers measure the three the same (tests/demo-mesh.test.ts).
//
//   node scripts/demo-mesh.mjs           writes examples/visual-tools/demo-tray.stl, demo-tray.obj and demo-tray.ply
//   node scripts/demo-mesh.mjs --check   exits 1 when a committed file is not what this script writes
//
// The tray: 80 × 50 × 20 (x, y, z; the file's own units, millimetres by the STL convention), walls 3 thick, a floor 2 thick,
// open at the top: a closed, consistently oriented mesh of 28 triangles, each one's corners counter-clockwise seen from
// outside (its stored normal is the corners' own), so Timmy's STL reader measures an enclosed volume of
// 80 × 50 × 20 − 74 × 44 × 18 = 21392.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { resolve } from 'node:path';

export const DEMO_MESH = 'examples/visual-tools/demo-tray.stl';
export const DEMO_OBJ = 'examples/visual-tools/demo-tray.obj';
export const DEMO_PLY = 'examples/visual-tools/demo-tray.ply';
/** The file's own words (at most 80 bytes): what made it, and what it is not. */
export const DEMO_HEADER = 'TIMMY DEMO MESH: generated by scripts/demo-mesh.mjs, not measured or exported';
export const DEMO_TRAY = { length: 80, width: 50, height: 20, wall: 3, floor: 2 };

/** The tray's triangles, each three corners [x, y, z], counter-clockwise seen from outside. */
export function trayTriangles({ length: L, width: W, height: H, wall: t, floor: f } = DEMO_TRAY) {
  const B = [[0, 0, 0], [L, 0, 0], [L, W, 0], [0, W, 0]];
  const O = B.map(([x, y]) => [x, y, H]);
  const I = [[t, t, H], [L - t, t, H], [L - t, W - t, H], [t, W - t, H]];
  const F = I.map(([x, y]) => [x, y, f]);
  const quad = (a, b, c, d) => [[a, b, c], [a, c, d]];
  const tris = [];
  tris.push([B[0], B[3], B[2]], [B[0], B[2], B[1]]); // the bottom, facing -z
  for (let k = 0; k < 4; k += 1) {
    const n = (k + 1) % 4;
    tris.push(...quad(B[k], B[n], O[n], O[k])); // an outer wall, facing out
    tris.push(...quad(O[k], O[n], I[n], I[k])); // the rim, facing +z
    tris.push([F[k], I[n], F[n]], [F[k], I[k], I[n]]); // an inner wall, facing into the pocket
  }
  tris.push([F[0], F[1], F[2]], [F[0], F[2], F[3]]); // the pocket's floor, facing +z
  return tris;
}

/** The demo mesh's bytes: the header, the count, then each triangle's unit normal, corners and a zero attribute. */
export function demoTrayStl() {
  const tris = trayTriangles();
  const b = Buffer.alloc(84 + 50 * tris.length);
  if (Buffer.byteLength(DEMO_HEADER, 'latin1') > 80) throw new Error('the header is longer than 80 bytes');
  b.write(DEMO_HEADER, 0, 'latin1');
  b.writeUInt32LE(tris.length, 80);
  tris.forEach(([a, c, d], i) => {
    const u = [c[0] - a[0], c[1] - a[1], c[2] - a[2]];
    const v = [d[0] - a[0], d[1] - a[1], d[2] - a[2]];
    const n = [u[1] * v[2] - u[2] * v[1], u[2] * v[0] - u[0] * v[2], u[0] * v[1] - u[1] * v[0]];
    const len = Math.hypot(...n);
    const at = 84 + i * 50;
    n.forEach((x, j) => b.writeFloatLE(x / len, at + j * 4));
    [a, c, d].forEach((p, k) => p.forEach((x, j) => b.writeFloatLE(x, at + 12 + k * 12 + j * 4)));
  });
  return b;
}

/**
 * The tray as corners and quads: its 16 corners in the order the triangles first name them, and each pair of triangles as one
 * quad [p0, p1, p2, p3] whose fan from its first corner, (p0, p1, p2) and (p0, p2, p3), is the pair, each corner list turned.
 */
export function trayQuads() {
  const tris = trayTriangles();
  const corners = [];
  const index = new Map();
  const id = (p) => { const k = p.join(','); if (!index.has(k)) { index.set(k, corners.length); corners.push(p); } return index.get(k); };
  const turns = (t) => [t, [t[1], t[2], t[0]], [t[2], t[0], t[1]]];
  const quads = [];
  for (let k = 0; k < tris.length; k += 2) {
    const [a, b] = [tris[k], tris[k + 1]].map((t) => t.map(id));
    const quad = turns(a).flatMap((p) => turns(b).filter((q) => p[0] === q[0] && p[2] === q[1]).map((q) => [p[0], p[1], p[2], q[2]]))[0];
    if (!quad) throw new Error(`triangles ${k + 1} and ${k + 2} are not one quad's fan`);
    quads.push(quad);
  }
  return { corners, quads };
}

/** The demo tray as a Wavefront OBJ: its first comment says what made it, then its object, corners and quads (from 1). */
export function demoTrayObj() {
  const { corners, quads } = trayQuads();
  return Buffer.from([`# ${DEMO_HEADER}`, 'o demo-tray', ...corners.map((p) => `v ${p.join(' ')}`), ...quads.map((q) => `f ${q.map((i) => i + 1).join(' ')}`), ''].join('\n'), 'latin1');
}

/** The demo tray as a binary little-endian PLY: float x, y, z and list uchar int vertex_indices, its first comment saying what made it. */
export function demoTrayPly() {
  const { corners, quads } = trayQuads();
  const header = ['ply', 'format binary_little_endian 1.0', `comment ${DEMO_HEADER}`, `element vertex ${corners.length}`, 'property float x', 'property float y', 'property float z',
    `element face ${quads.length}`, 'property list uchar int vertex_indices', 'end_header', ''].join('\n');
  const data = Buffer.alloc(corners.length * 12 + quads.length * 17);
  let at = 0;
  for (const p of corners) for (const x of p) { data.writeFloatLE(x, at); at += 4; }
  for (const q of quads) { data.writeUInt8(4, at); at += 1; for (const i of q) { data.writeInt32LE(i, at); at += 4; } }
  return Buffer.concat([Buffer.from(header, 'latin1'), data]);
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  let failed = false;
  for (const [name, want] of [[DEMO_MESH, demoTrayStl()], [DEMO_OBJ, demoTrayObj()], [DEMO_PLY, demoTrayPly()]]) {
    const file = fileURLToPath(new URL(`../${name}`, import.meta.url));
    if (process.argv.includes('--check')) {
      let have = Buffer.alloc(0);
      try { have = readFileSync(file); } catch { /* missing */ }
      if (!have.equals(want)) { console.error(`${name} is not what scripts/demo-mesh.mjs writes: run it again`); failed = true; continue; }
      console.log(`${name}: as scripts/demo-mesh.mjs writes it (${want.length} bytes)`);
    } else {
      writeFileSync(file, want);
      console.log(`wrote ${name} (${want.length} bytes, generated: not measured or exported)`);
    }
  }
  if (failed) process.exit(1);
}
