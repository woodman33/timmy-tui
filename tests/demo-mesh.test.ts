/**
 * R7 (H153): the review package's demo mesh (examples/visual-tools/demo-tray.stl), made by a committed script
 * (scripts/demo-mesh.mjs) and labelled as generated in its own header: the committed file is exactly what the script writes,
 * the package ships it, Timmy's own STL reader measures it as the closed tray the script describes, and tab 6's list shows
 * its header's words (declared by the file, not checked).
 *
 * R8 (H154): the same tray as demo-tray.obj and demo-tray.ply, written by the same script from the same triangles (each quad's
 * fan gives the STL's two triangles, in the STL's order) and labelled as generated in their own first comment: each committed
 * file is what the script writes, `--check` says so for all three, and the measurements of the three by Timmy's own STL, OBJ and
 * PLY readers agree, field for field; tab 6 lists the three kinds with the same measurements and each file's own words.
 */
import { execFileSync } from 'node:child_process';
import { copyFileSync, mkdirSync, mkdtempSync, readFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { describe, expect, it } from 'vitest';
import { readObjFile } from '../src/native/obj-readback.js';
import { readPlyFile } from '../src/native/ply-readback.js';
import { readStlFile, type MeshMeasure } from '../src/native/stl-readback.js';
import { listMeshes } from '../src/vox/meshes.js';
import { DEMO_HEADER, DEMO_MESH, DEMO_OBJ, DEMO_PLY, demoTrayObj, demoTrayPly, demoTrayStl } from '../scripts/demo-mesh.mjs';

const MEASURES = ['triangles', 'corners', 'bbox', 'volume', 'area', 'edges', 'boundary_edges', 'non_manifold_edges', 'misoriented_edges', 'collapsed_triangles', 'zero_area_triangles', 'manifold', 'oriented'] as const;
const measures = (m: MeshMeasure) => Object.fromEntries(MEASURES.map((k) => [k, m[k]]));

describe('the demo mesh (R7 H153)', () => {
  it('is exactly what scripts/demo-mesh.mjs writes, ships in the package, and says it is generated, not measured or exported', () => {
    const file = resolve(DEMO_MESH);
    expect(readFileSync(file).equals(demoTrayStl())).toBe(true);
    const pkg = JSON.parse(readFileSync('package.json', 'utf8')) as { files: string[] };
    expect(pkg.files).toContain('examples/visual-tools');
    expect(DEMO_HEADER).toBe('TIMMY DEMO MESH: generated by scripts/demo-mesh.mjs, not measured or exported');
    expect(readFileSync(file).subarray(0, 80).toString('latin1').replace(/\0+$/, '')).toBe(DEMO_HEADER);
  });

  it('Timmy\'s own STL reader measures it as the closed tray the script describes', () => {
    const r = readStlFile(resolve(DEMO_MESH), DEMO_MESH);
    expect(r.ok).toBe(true);
    if (!r.ok) return;
    expect(r.readback).toMatchObject({
      format: 'binary', triangles: 28, corners: 16, bbox: { min: [0, 0, 0], max: [80, 50, 20], size: [80, 50, 20] },
      manifold: true, oriented: true, boundary_edges: 0, non_manifold_edges: 0, misoriented_edges: 0,
    });
    expect(r.readback.volume).toBeCloseTo(80 * 50 * 20 - 74 * 44 * 18, 6);
  });

  it('tab 6\'s list shows its header as the file\'s own words', () => {
    const box = mkdtempSync(join(tmpdir(), 'r7-demo-mesh-'));
    try {
      const root = join(box, 'FAKE-tray');
      mkdirSync(join(root, 'refs'), { recursive: true });
      copyFileSync(resolve(DEMO_MESH), join(root, 'refs', 'demo-tray.stl'));
      const [row] = listMeshes({ root, env: { PATH: '' } }).meshes;
      expect(row.path).toBe('refs/demo-tray.stl');
      expect(row.declared).toEqual({ words: DEMO_HEADER, what: 'its 80-byte header' });
      expect(row.view).toEqual({ shown: 28, total: 28, words: 'all 28 triangles' });
    } finally { rmSync(box, { recursive: true, force: true }); }
  });
});

describe('the demo tray as OBJ and PLY (R8 H154)', () => {
  it('each is exactly what scripts/demo-mesh.mjs writes, labelled as generated in its first comment; --check says so for all three', () => {
    expect([DEMO_OBJ, DEMO_PLY]).toEqual(['examples/visual-tools/demo-tray.obj', 'examples/visual-tools/demo-tray.ply']);
    expect(readFileSync(resolve(DEMO_OBJ)).equals(demoTrayObj())).toBe(true);
    expect(readFileSync(resolve(DEMO_PLY)).equals(demoTrayPly())).toBe(true);
    expect(demoTrayObj().toString('latin1').split('\n')[0]).toBe(`# ${DEMO_HEADER}`);
    expect(demoTrayPly().toString('latin1').split('\n').slice(0, 3)).toEqual(['ply', 'format binary_little_endian 1.0', `comment ${DEMO_HEADER}`]);
    const said = execFileSync(process.execPath, ['scripts/demo-mesh.mjs', '--check'], { encoding: 'utf8' });
    expect(said.trim().split('\n')).toEqual([
      `${DEMO_MESH}: as scripts/demo-mesh.mjs writes it (${demoTrayStl().length} bytes)`,
      `${DEMO_OBJ}: as scripts/demo-mesh.mjs writes it (${demoTrayObj().length} bytes)`,
      `${DEMO_PLY}: as scripts/demo-mesh.mjs writes it (${demoTrayPly().length} bytes)`,
    ]);
  });

  it('the measurements of the three by Timmy\'s own STL, OBJ and PLY readers agree, field for field', () => {
    const stl = readStlFile(resolve(DEMO_MESH), DEMO_MESH);
    const obj = readObjFile(resolve(DEMO_OBJ), DEMO_OBJ);
    const ply = readPlyFile(resolve(DEMO_PLY), DEMO_PLY);
    if (!stl.ok) throw new Error(stl.error);
    if (!obj.ok) throw new Error(obj.error);
    if (!ply.ok) throw new Error(ply.error);
    expect(measures(obj.readback)).toEqual(measures(stl.readback));
    expect(measures(ply.readback)).toEqual(measures(stl.readback));
    // the area: the bottom, the outer walls, the rim, the inner walls (18 high) and the pocket's floor
    expect(stl.readback).toMatchObject({ triangles: 28, corners: 16, area: 80 * 50 + 2 * 20 * (80 + 50) + (80 * 50 - 74 * 44) + 2 * 18 * (74 + 44) + 74 * 44, manifold: true, oriented: true });
    // the signed volume's sum about the box's centre is not exact in binary fractions (21392.000000000004): the three agree
    // exactly above, and each is 21392 to six places
    for (const r of [stl, obj, ply]) expect(r.readback.volume).toBeCloseTo(21392, 6);
    expect(obj.readback.obj).toMatchObject({ vertices: 16, faces: 14, polygons: 14, unused_vertices: 0, ignored_words: 'ignored: 1 comment, 1 o lines' });
    expect(ply.readback.ply).toMatchObject({ encoding: 'binary_little_endian', vertices: 16, faces: 14, polygons: 14, unused_vertices: 0, coordinates: 'x, y and z as float', indices: 'list uchar int vertex_indices', ignored_words: 'ignored: 1 comment line' });
  });

  it('tab 6 lists the three kinds with the same measurements in the same words, and each file\'s own words', () => {
    const box = mkdtempSync(join(tmpdir(), 'r8-demo-mesh-'));
    try {
      const root = join(box, 'FAKE-tray');
      mkdirSync(join(root, 'refs'), { recursive: true });
      for (const f of [DEMO_MESH, DEMO_OBJ, DEMO_PLY]) copyFileSync(resolve(f), join(root, 'refs', f.split('/').pop()!));
      const rows = listMeshes({ root, env: { PATH: '' } }).meshes;
      expect(rows.map((m) => [m.path, m.kind, m.reader.id, m.format])).toEqual([
        ['refs/demo-tray.obj', 'obj', 'timmy-obj-readback/1', 'Wavefront OBJ (text)'],
        ['refs/demo-tray.ply', 'ply', 'timmy-ply-readback/1', 'PLY (binary little-endian)'],
        ['refs/demo-tray.stl', 'stl', 'timmy-stl-readback/1', 'binary STL'],
      ]);
      for (const m of rows) {
        expect([m.topology, m.volume, m.view], m.path).toEqual(['edge-manifold: every edge shared by exactly two triangles, consistently oriented', '21392 (enclosed; normals outward)', { shown: 28, total: 28, words: 'all 28 triangles' }]);
        expect(m.declared?.words, m.path).toBe(DEMO_HEADER);
      }
      expect(rows.map((m) => m.declared?.what)).toEqual(['its first comment', "its header's first comment", 'its 80-byte header']);
    } finally { rmSync(box, { recursive: true, force: true }); }
  });
});
