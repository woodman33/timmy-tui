/**
 * R7 (H153): the review package's demo mesh (examples/visual-tools/demo-tray.stl), made by a committed script
 * (scripts/demo-mesh.mjs) and labelled as generated in its own header: the committed file is exactly what the script writes,
 * the package ships it, Timmy's own STL reader measures it as the closed tray the script describes, and tab 6's list shows
 * its header's words (declared by the file, not checked).
 */
import { copyFileSync, mkdirSync, mkdtempSync, readFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { describe, expect, it } from 'vitest';
import { readStlFile } from '../src/native/stl-readback.js';
import { listMeshes } from '../src/vox/meshes.js';
import { DEMO_HEADER, DEMO_MESH, demoTrayStl } from '../scripts/demo-mesh.mjs';

describe('the demo mesh (R7 H153)', () => {
  it('is exactly what scripts/demo-mesh.mjs writes, ships in the package, and says it is generated, not measured or exported', () => {
    const file = resolve(DEMO_MESH);
    expect(readFileSync(file).equals(demoTrayStl())).toBe(true);
    const pkg = JSON.parse(readFileSync('package.json', 'utf8')) as { files: string[] };
    expect(pkg.files).toContain('examples/visual-tools');
    expect(DEMO_HEADER).toBe('TIMMY DEMO MESH: generated by scripts/demo-mesh.mjs, not measured or exported');
    expect(readFileSync(file).subarray(0, 80).toString('latin1').replace(/\0+$/, '')).toBe(DEMO_HEADER);
  });

  it('Timmy\'s own STL reader measures it as the closed tray the script describes', () => {
    const r = readStlFile(resolve(DEMO_MESH), DEMO_MESH);
    expect(r.ok).toBe(true);
    if (!r.ok) return;
    expect(r.readback).toMatchObject({
      format: 'binary', triangles: 28, corners: 16, bbox: { min: [0, 0, 0], max: [80, 50, 20], size: [80, 50, 20] },
      manifold: true, oriented: true, boundary_edges: 0, non_manifold_edges: 0, misoriented_edges: 0,
    });
    expect(r.readback.volume).toBeCloseTo(80 * 50 * 20 - 74 * 44 * 18, 6);
  });

  it('tab 6\'s list shows its header as the file\'s own words', () => {
    const box = mkdtempSync(join(tmpdir(), 'r7-demo-mesh-'));
    try {
      const root = join(box, 'FAKE-tray');
      mkdirSync(join(root, 'refs'), { recursive: true });
      copyFileSync(resolve(DEMO_MESH), join(root, 'refs', 'demo-tray.stl'));
      const [row] = listMeshes({ root, env: { PATH: '' } }).meshes;
      expect(row.path).toBe('refs/demo-tray.stl');
      expect(row.declared).toEqual({ words: DEMO_HEADER, what: 'its 80-byte header' });
      expect(row.view).toEqual({ shown: 28, total: 28, words: 'all 28 triangles' });
    } finally { rmSync(box, { recursive: true, force: true }); }
  });
});
